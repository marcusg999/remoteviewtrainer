/**
 * REMOTE VIEWING — Coordinate Remote Viewing protocol, honestly implemented.
 *
 * ===================================================================
 * INTERFACE (this is what main.js wires up)
 * ===================================================================
 *
 *   import { RemoteViewRun, STAGES, TRIALS, CHANCE } from './modes/remoteview.js';
 *
 *   const run = new RemoteViewRun(ctx, opts);
 *   const { coordinate } = await run.begin();   // seals the target; MUST be awaited first
 *   run.mountUI(hostEl);                        // builds the whole stage UI inside hostEl
 *   const report = await run.finish();          // resolves when the viewer commits a ranking
 *   run.dispose();
 *
 *   ctx   = { scene, particles, floatText, director, tweens, onUpdate }
 *           Every field is optional — the mode is DOM-first and only uses the 3D
 *           juice if it is handed some. onUpdate(snapshot) fires on every stage
 *           change and every ranking change.
 *   opts  = {
 *     pool:        Target[]  (default TARGETS from ../data/targets.js)
 *     candidates:  5         how many targets the ranking stage shows
 *     ideogramMs:  9000      soft window for the reflexive stroke
 *     autoLog:     true      finish() writes the session to the career log itself
 *     onStage:     fn(stageId, index)
 *   }
 *
 *   report() — same shape as ZenerRun.report(): everything summarize() returns,
 *   plus mode/results/durationMs/proof, plus the remote-viewing specifics
 *   (coordinate, target, candidates, ranking, impressions, sketches).
 *
 *   Also exported: STAGES (the default stage list), TRIALS, CHANCE,
 *   SENSORY_CATEGORIES, buildRevealBlock(report) → an element for the result
 *   modal, and verifyRun(report) → re-checks the commitment.
 *
 * ===================================================================
 * PROTOCOL — the part that must not be fudged
 * ===================================================================
 *
 * 1. COORDINATE. An 8-digit reference is generated by randomCoordinate(), which
 *    is pure CSPRNG output. It is generated BEFORE the target is drawn and the
 *    target is never derived from it, hashed with it, or indexed by it — see
 *    begin(), where the ordering makes the independence structural rather than
 *    a promise. The coordinate is a LABEL, exactly as in the original protocol:
 *    it carries no information whatsoever about what the target is. Two runs
 *    with the same coordinate would be two independent draws.
 *
 * 2. SEALED BEFORE THE SESSION. The target and the whole candidate set are
 *    chosen, then committed with SHA-256 via seal() before mountUI() can paint
 *    anything and before the viewer records a single impression. The salt is
 *    published in the report at the end, so anyone can recompute
 *    SHA-256(salt + ":" + payload) and prove the target did not change after
 *    the ranking. Same guarantee zener.js gives, same code path.
 *
 * 3. FAIR CANDIDATES. chooseTargetSet() in ../data/targets.js draws the true
 *    target uniformly from the pool, the decoys uniformly WITHOUT REPLACEMENT
 *    from the pool minus the true target, and then shuffles the display order
 *    independently with Fisher-Yates. So: a decoy is never the true target, no
 *    target appears twice, and grid position leaks nothing. Chance of a
 *    first-place hit is exactly 1/5 = 20%.
 *
 * 4. NO Math.random ANYWHERE THAT MATTERS. Every draw goes through core/rng.js
 *    (crypto.getRandomValues with rejection sampling). Math.random appears in
 *    this file exactly once, for the cosmetic position jitter of a particle
 *    burst, and is labelled where it happens.
 *
 * 5. NO ADAPTIVE DIFFICULTY. The pool, the candidate count and the chance level
 *    are constants. Nothing in this file reads the career log, the current
 *    score, or any history before choosing a target. A run cannot be made
 *    easier or harder by how the viewer has been doing.
 *
 * 6. SCORING. A hit is ranking the true target FIRST. Anything else is a miss.
 *    trials = 1, hits ∈ {0,1}, chance = 0.2. Second place is reported for
 *    interest but is NOT scored, because scoring it would change the null and
 *    the honest p-value with it.
 */
