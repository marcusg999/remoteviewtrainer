/**
 * The reveal block: the true target drawn large, the viewer's own ideogram and
 * sketch beside it, and which of the target's tags the viewer actually named.
 * Returns a detached element — drop it into the result panel.
 */
export function buildRevealBlock(report) {
  const wrap = el('div', 'rv-reveal');
  const canvas = el('canvas', 'rv-reveal-art');
  wrap.appendChild(canvas);
  wrap.appendChild(el('h3', 'rv-reveal-name',
    `${report.target.name}${report.hit ? '' : ` &middot; you ranked it ${report.rankOfTarget ? ORDINAL[report.rankOfTarget] : 'nowhere'}`}`));
  wrap.appendChild(el('p', 'rv-reveal-desc', report.target.describe));

  if (report.target.tags?.length) {
    const tags = el('div', 'rv-tags');
    const hit = new Set(report.matchedTags || []);
    for (const t of report.target.tags) {
      const c = el('span', `rv-tag${hit.has(t) ? ' match' : ''}`, t);
      tags.appendChild(c);
    }
    wrap.appendChild(tags);
  }

  if (report.ideogram?.png || report.sketch?.png) {
    const side = el('div', 'rv-sidebyside');
    for (const [key, caption] of [['ideogram', 'Your ideogram'], ['sketch', 'Your sketch']]) {
      if (!report[key]?.png) continue;
      const fig = el('figure');
      const img = el('img');
      img.src = report[key].png;
      img.alt = caption;
      fig.appendChild(img);
      fig.appendChild(el('figcaption', null, caption));
      side.appendChild(fig);
    }
    wrap.appendChild(side);
  }

  // Paint once the element has a measurable width.
  const paint = () => {
    const t = TARGETS.find((x) => x.id === report.target.id);
    if (!t) return;
    if (!canvas.clientWidth) { requestAnimationFrame(paint); return; }
    paintTarget(canvas, t);
  };
  requestAnimationFrame(paint);
  return wrap;
}

/** Re-check a finished run's commitment. Pure verification; no side effects. */
export async function verifyRun(report) {
  const p = report?.proof?.[0];
  if (!p) return false;
  if (!p.payload.includes(`target=${report.target.id}`)) return false;
  if (!p.payload.startsWith(`rv:${report.coordinate}:`)) return false;
  return verify(p);
}

